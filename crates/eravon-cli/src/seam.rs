pub fn proposal_doc_path(proposal: &str, name: &str) -> Result<String, String> {
    let dir = std::path::Path::new(proposal).parent().filter(|d| !d.as_os_str().is_empty()).unwrap_or(std::path::Path::new("."));
    eravon_literals::seam::named_under(dir, name).map(|p| p.display().to_string())
}

