pub fn desk_names() -> Vec<&'static str> {
    Vec::new()
}

pub fn desk_reason(code: &str) -> Option<(Reason, Option<&'static str>)> {
    if let Some((c, name)) = DESK.iter().find(|(c, _)| *c == code) {
        return Some((Reason::of_name(name)?, (c != name).then_some(*c)));
    }
    Reason::of_name(code).or_else(|| Reason::of_name(&format!("E_{}", code.to_ascii_uppercase()))).map(|r| (r, None))
}

