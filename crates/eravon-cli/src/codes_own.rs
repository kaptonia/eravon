#[cfg(test)]
mod exit_sets {
    use super::Reason;
    use eravon_literals::schema::{PARTIAL, UNANSWERED};

    #[test]
    fn every_name_the_door_exits_three_or_four_with_is_in_its_closed_set() {
        let mut four: Vec<&str> = vec![Reason::Desktop.as_str(), Reason::OutcomeLost.as_str()];
        for k in eravon_vault::fault::Known::NETWORK {
            if let Some((r, _)) = super::desk_reason(k.as_str()) {
                four.push(r.as_str());
            }
        }
        let three = [Reason::Queued.as_str()];
        assert_eq!(crate::verbs::queued(1).exit, crate::codes::Exit::Partial, "a queued write exits 3");
        let lacking = |set: &[&str], names: &[&str]| names.iter().filter(|n| !set.contains(n)).map(|n| n.to_string()).collect::<Vec<_>>();
        assert_eq!(lacking(UNANSWERED, &four), Vec::<String>::new(), "names through the door that exit 4");
        assert_eq!(lacking(PARTIAL, &three), Vec::<String>::new(), "names through the door that exit 3");
        let was: &[&str] = &["E_V_UNCONFIRMED"];
        assert!(!lacking(was, &three).is_empty(), "the counter-example: the register as it stood lacks the queued write");
    }
}
