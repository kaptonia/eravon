#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Held {
    Locked,
}

impl Held {
    pub fn said(self, lang: crate::house::i18n::Lang) -> (&'static str, crate::house::shell::Toast) {
        let (name, next) = match self {
            Held::Locked => ("E_VAULT_LOCKED", crate::house::i18n::get(lang, crate::house::i18n::Key::ErrEVAULTLOCKEDNext).0),
        };
        let head = crate::house::refusal::what(lang, name).unwrap_or_else(|| name.to_string());
        (name, crate::house::shell::Toast { tone: crate::house::seller::Tone::Bad, head, next, detail: Some(name.to_string()) })
    }
}

pub fn held_back(a: Action, locked: bool) -> Option<Held> {
    (locked && (a.needs_key() || a.halts_when_locked())).then_some(Held::Locked)
}

